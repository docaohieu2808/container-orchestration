#!/usr/bin/env bash
# Validate every Kubernetes manifest in the repo with kubeconform in -strict mode against the current
# Kubernetes schemas, including the custom resources the ladder uses (WebApp, Traefik, System Upgrade
# Controller). CRD schemas are not guessed or skipped: they are converted from the real CRD files.
#
# Needs: kubeconform, python3 with PyYAML, curl.   Usage: bash ci/kubeconform-all-manifests.sh
set -euo pipefail

K8S_VERSION="${K8S_VERSION:-1.37.0}"
KUBECONFORM_TAG="${KUBECONFORM_TAG:-v0.8.0}"   # the converter script is taken from the same tag
TRAEFIK_TAG="${TRAEFIK_TAG:-v3.7.16}"
SUC_TAG="${SUC_TAG:-v0.20.2}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT
SCHEMAS="${WORK}/schemas"
mkdir -p "${SCHEMAS}"

curl -fsSL "https://raw.githubusercontent.com/yannh/kubeconform/${KUBECONFORM_TAG}/scripts/openapi2jsonschema.py" \
  -o "${WORK}/openapi2jsonschema.py"
curl -fsSL "https://raw.githubusercontent.com/traefik/traefik/${TRAEFIK_TAG}/docs/content/reference/dynamic-configuration/kubernetes-crd-definition-v1.yml" \
  -o "${WORK}/traefik-crds.yml"
curl -fsSL "https://github.com/rancher/system-upgrade-controller/releases/download/${SUC_TAG}/crd.yaml" \
  -o "${WORK}/suc-crds.yml"

# One JSON schema per CRD version, named <kind>_<version>.json (lower case), written to the cwd.
(cd "${SCHEMAS}" && python3 "${WORK}/openapi2jsonschema.py" \
  "${ROOT}/kubernetes/l4-operators-crds/crd-webapp-custom-resource-definition.yaml" \
  "${WORK}/traefik-crds.yml" "${WORK}/suc-crds.yml" >/dev/null)
echo "CRD schemas: $(find "${SCHEMAS}" -name '*.json' | wc -l) files"

# Everything that is a Kubernetes manifest. The k3s node config files (registries.yaml, config.yaml
# snippets) are not API objects and are covered by yamllint instead.
mapfile -t FILES < <(cd "${ROOT}" && find kubernetes k3s -name '*.yaml' \
  ! -name 'k3s-registries-mirror-config.yaml' \
  ! -name 'embedded-registry-spegel-config.yaml' \
  ! -name 'etcd-snapshot-s3-server-config.yaml' \
  ! -name 'podinfo-values-override.yaml' | sort)

# CustomResourceDefinition itself has no published JSON schema (it is served by the API extension server),
# so it is skipped here: it is generated by controller-gen (drift-checked in the go job) and applied to a real
# API server in the kind job, which validates it for real.
cd "${ROOT}"
kubeconform -strict -summary -verbose \
  -skip CustomResourceDefinition \
  -kubernetes-version "${K8S_VERSION}" \
  -schema-location default \
  -schema-location "${SCHEMAS}/{{ .ResourceKind }}_{{ .ResourceAPIVersion }}.json" \
  "${FILES[@]}"
